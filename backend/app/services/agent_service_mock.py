"""Mock agent service for Phase 6 MVP testing (temporary)."""

from __future__ import annotations

from uuid import UUID, uuid4

from app.services.agent_service import AgentRunResult


class MockAgentService:
    """Simple mock agent service for basic report generation during Phase 6 MVP."""

    async def run(
        self,
        *,
        project_id: UUID,
        request: str,
        conversation_id: UUID | None = None,
    ) -> AgentRunResult:
        """Generate a basic mock research report."""
        run_id = uuid4()
        message_id = uuid4()

        # Generate basic content based on request type
        if "literature review" in request.lower():
            answer = self._generate_literature_review(request)
        elif "gap analysis" in request.lower():
            answer = self._generate_gap_analysis(request)
        elif "source comparison" in request.lower():
            answer = self._generate_source_comparison(request)
        elif "survey" in request.lower():
            answer = self._generate_survey(request)
        else:
            answer = self._generate_generic_report(request)

        return AgentRunResult(
            run_id=run_id,
            message_id=message_id,
            answer=answer,
            citations=[],  # Empty for MVP
            sources=[],   # Empty for MVP
            citation_warning=True,  # Since we have no real citations
            degraded=True,  # This is a mock service
            degraded_reason="Using mock agent service for Phase 6 MVP"
        )

