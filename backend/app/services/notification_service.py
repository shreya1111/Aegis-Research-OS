"""In-app notifications for long-running work (Phase 10, FR-H8).

A report artifact is generated by a background task, so the user needs a place
to learn it finished. Notifications are per-user and optional-link: everything
else about the artifact stays in ``reports``.
"""

from __future__ import annotations

from uuid import UUID

from app.core.errors import NotFoundError
from app.db.models.notification import Notification, NotificationType
from app.db.repositories.notification_repository import NotificationRepository


class NotificationService:
    """Create and read per-user in-app notifications."""

    def __init__(self, *, notification_repository: NotificationRepository) -> None:
        self._notifications = notification_repository

    async def notify(
        self,
        *,
        user_id: UUID,
        title: str,
        message: str,
        type: str,
        project_id: UUID | None = None,
        link: str | None = None,
    ) -> Notification:
        return await self._notifications.create(
            user_id=user_id,
            type=type,
            title=title,
            message=message,
            project_id=project_id,
            link=link,
        )

    async def notify_report_completed(
        self,
        *,
        user_id: UUID,
        project_id: UUID,
        report_title: str,
        succeeded: bool,
    ) -> Notification:
        """Tell the requesting user their artifact finished (or failed)."""
        if succeeded:
            return await self.notify(
                user_id=user_id,
                project_id=project_id,
                type=NotificationType.REPORT_COMPLETED,
                title="Report ready",
                message=f"“{report_title}” finished generating.",
                link=f"/projects/{project_id}/reports",
            )
        return await self.notify(
            user_id=user_id,
            project_id=project_id,
            type=NotificationType.REPORT_COMPLETED,
            title="Report failed",
            message=f"“{report_title}” could not be generated.",
            link=f"/projects/{project_id}/reports",
        )

    async def list_for_user(self, *, user_id: UUID, limit: int = 20) -> list[Notification]:
        return await self._notifications.list_for_user(user_id=user_id, limit=limit)

    async def unread_count(self, *, user_id: UUID) -> int:
        return await self._notifications.count_unread(user_id=user_id)

    async def mark_read(self, notification_id: UUID, *, user_id: UUID) -> None:
        """Mark one notification read, raising 404 for a foreign or missing id."""
        marked = await self._notifications.mark_read(notification_id, user_id=user_id)
        if not marked:
            raise NotFoundError("Notification not found.")
